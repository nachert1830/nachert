/* корни f(s) на [lo, hi] — по смене знака на сетке, уточнение делением пополам */
function roots(f,lo,hi,N){ const out=[]; let a=lo, fa=f(a); for(let i=1;i<=N;i++){ const b=lo+(hi-lo)*i/N, fb=f(b);
    if(Number.isFinite(fa)&&Number.isFinite(fb)&&fa*fb<0){ let x=a,y=b,fx=fa; for(let k=0;k<80;k++){ const m=(x+y)/2, fm=f(m); if(fx*fm<=0) y=m; else { x=m; fx=fm; } } out.push((x+y)/2); } a=b; fa=fb; } return out; }

