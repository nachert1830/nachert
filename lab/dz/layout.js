function parseLayout(text,k,W,H){ const a=String(text||''), i=a.indexOf('{'), j=a.lastIndexOf('}'); let o=null; try{ o=JSON.parse(a.slice(i,j+1)); }catch(e){}
  if(!o||!Array.isArray(o.drawings)) return {ok:false,why:'раскладка не разобрана',rot:0,drawings:[]};
  const rot=[0,90,180,270].includes(+o.rot)?+o.rot:0, dr=[];
  o.drawings.forEach(d=>{ const b=d&&d.box; if(!Array.isArray(b)||b.length!==4||!b.every(Number.isFinite)) return;
    const x0=Math.max(0,Math.min(b[0],b[2])*k), y0=Math.max(0,Math.min(b[1],b[3])*k), x1=Math.min(W,Math.max(b[0],b[2])*k), y1=Math.min(H,Math.max(b[1],b[3])*k);
    if(x1-x0<W*0.08||y1-y0<H*0.08) return; dr.push({box:[x0,y0,x1,y1],part:d.part==null?null:+d.part}); });
  return {ok:dr.length>0,why:dr.length?'':'чертежей не найдено',rot,drawings:dr}; }

function parseDigit(text){ const pts=[], segs=[], txt=[]; let bad=0;
  String(text||'').split(/\r?\n/).forEach(l=>{ const L=l.replace(/[*`|]/g,' ').replace(/[(),;]/g,' ').trim(), t=L.split(/\s+/);
    if(t[0]==='S'&&t.length>=5){ const q=t.slice(1,5).map(Number); if(q.every(Number.isFinite)) segs.push(q.concat(t[5]==='d'?[1]:[])); else bad++; }
    else if(t[0]==='P'&&t.length>=4){ const x=+t[2], y=+t[3]; if(isFinite(x)&&isFinite(y)) pts.push([t[1],x,y]); else bad++; }
    else if(t[0]==='T'&&t.length>=4){ const x=+t[1], y=+t[2]; if(isFinite(x)&&isFinite(y)) txt.push([x,y,t.slice(3).join(' ')]); } });
  return {pts,segs,txt,bad}; }
