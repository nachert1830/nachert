function specText(s) {
  if (!s) return '';
  const L = a => (a || []).filter(Boolean).map(x => '- ' + x).join('\n');
  return ['# ' + (s.title || 'Задача'), s.what ? '\n' + s.what : '', s.where ? '\n**Где:** ' + s.where : '',
    s.done && s.done.length ? '\n**Готово, когда:**\n' + L(s.done) : '', s.not && s.not.length ? '\n**Не делать:**\n' + L(s.not) : '',
    s.test ? '\n**Проверка:** ' + s.test : '', s.epic ? '\n' + s.epic : ''].join('\n').trim();
}

