/* карточка варианта — второе системное сообщение (меняется от варианта к варианту) */
function card(ctx){ const o=ctx.overview, L=[];
  L.push(`${o.label} · вариант ${o.variant}: ${o.body}.`);
  L.push('Задание: '+o.task);
  L.push('Шаги решения: '+o.steps.map(s=>s.k+'. '+s.title).join('; ')+'.');
  L.push('Режим: '+(ctx.mode==='explain'?'«Разбор» — лесенка снята, объясняй полностью.':'«Наставник» — лесенка подсказок.'));
  if(ctx.step) L.push('Сейчас у студента на экране шаг '+ctx.step+(o.steps[ctx.step-1]?' («'+o.steps[ctx.step-1].title+'»)':'')+'.');
  if(ctx.memo) L.push('Что известно о студенте по этому варианту: '+ctx.memo);
  if(ctx.photo) L.push('К этому сообщению студент приложил фото своего листа.');
  if(ctx.inline) L.push('Инструментов сейчас нет. Открытое студенту по текущему шагу (говори только об этом):\n'+ctx.inline);
  return L.join('\n'); }

