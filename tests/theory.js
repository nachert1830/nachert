const QZ=/\{\s*q:\s*'((?:[^'\\]|\\.)*)'\s*,\s*o:\s*\[((?:\s*'(?:[^'\\]|\\.)*'\s*,?)+)\]\s*,\s*c:\s*(\d+)/g;
