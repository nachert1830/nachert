/* ═══════════ Инженерная графика · Задание №8 · 3D-модели вариантов ═══════════
   Дерево IG3.P (мм; z вверх; x вправо; смотрим спереди вдоль +y), как у ДЗ 4 и 5: по нему сайт строит виды, 3D, полуразрезы,
   разрез А–А, шаги и лист. Центр шара — начало координат. Модели строятся при первом обращении. */
(function(){
let cache=null;
function build(){
  const {P}=IG3, S=P.S, V={};
  const sph=r=>({t:'sph',r});
  /* 6 — полый шар: снаружи Ø110, полость Ø80. K — сквозное отверстие вдоль y (⟂ π₂), профиль на главном виде:
     цилиндр Ø45 по центру; паз шириной 20 — от центра вверх насквозь и вниз до z −30; прямоугольник 40 на z −45…−30
     (размеры 45 и 15 — от горизонтальной оси). Вид сверху в задании — только шар и полость (штриховая Ø80). */
  const shell=S(sph(55),sph(40));
  V[6]={n:6,title:'Полый шар со сквозным отверстием',H:110,box:[[-55,-55,-55],[55,55,55]],
    tree:S(sph(55),sph(40),P.box(20,400,-31,60),P.hcyl('y',22.5,[0,0],-70,70),P.box(40,400,-45,-30)),
    givenTop:shell,noGivenDims:true,hz:{L:'А',z:0},spec:{F:'half',L:'half'},hzRight:true,
    why:'Любая плоскость режет шар по окружности радиуса √(R² − d²). Горизонтальные грани K (z −30, z −45) дают дуги на виде сверху, вертикальные (x ±10, x ±20) — дуги на виде слева; цилиндр Ø45 соосен шару и выходит на сферы по окружностям, на видах сверху и слева — отрезки. Полость Ø80 режут только грани ближе 40 мм от центра: z −45 проходит по стенке.',
    /* размеры — как в условии; шар — «Сфера Ø» (ГОСТ 2.307). Ø110 и Ø80 — на разрезе А–А (обе сферы там — окружности
       в натуральную величину; выноски — как на виде сверху в условии), Ø45 и контур K — на главном виде; ширина паза 20 —
       внутри паза, чтобы лист уложился в А3 */
    dims:[['F','h',[-10,40],[10,40],40,'20',{fix:1,tx:-5}],['F','h',[-20,-45],[20,-45],-68,'40'],
      ['F','v',[20,-30],[20,-45],68,'15'],['F','v',[55,0],[20,-45],80,'45'],['F','dia',[0,0],45,30,42,'Ø45',-1],
      ['T','dia',[0,0],110,-30,12,'Сфера Ø110',-1],['T','dia',[0,0],80,30,30,'Сфера Ø80',-1]]};
  return V; }
DZR.def('ig8',{parts(){ return cache||(cache=build()); },part(n){ return this.parts()[+n]||null; }});
})();
