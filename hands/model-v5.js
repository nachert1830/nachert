/* Модель «вариант 5» (задача 2): фланец + усечённый конус, сквозное пирамидальное отверстие, 4 отверстия во фланце.
   Описание для рендерера: данные, раскладка «разбора», подписи, вопросы теста. Механизма и потока нет. */
import data from './v5.js';

const sm = x => { x = Math.max(0, Math.min(1, x)); return x * x * (3 - 2 * x); };

export default {
  key: 'v5', title: 'Вариант 5', data,
  /* раскладка: смещения частей, поворотов нет; пробки (вынутый материал) проявляются, когда тела разошлись */
  layout(e) {
    const u1 = sm(e / 0.5), u2 = sm((e - 0.3) / 0.7), up = sm(u2 / 0.55), side = sm((u2 - 0.45) / 0.55), gap = 40 * u1;
    const hole = [0, 0, -gap - 48 * u2];
    return { off: { flange: [0, 0, -gap], cone: [0, 0, gap], pyr: [105 * side, 0, gap + 175 * up - 135 * side], hole0: hole, hole1: hole, hole2: hole, hole3: hole },
      rot: {}, plugA: sm((e - 0.04) / 0.12) };
  },
  /* указка: 4 отверстия — одна «часть» */
  group: id => (id.startsWith('hole') ? 'holes' : id),
  labels: {
    flange: { z: 12.5, r: 55, side: 1, s: 'Фланец Ø110', t: 'Фланец', d: 'цилиндр Ø110, высота 25' },
    cone: { z: 75, r: 34, side: -1, s: 'Конус Ø80→Ø60', t: 'Усечённый конус', d: 'Ø80 → Ø60, высота 95' },
    pyr: { z: 112, r: 12, side: 1, s: 'Пирамида-отверстие', t: 'Сквозное отверстие', d: 'правильная трёхгранная пирамида, вписана в Ø25 → Ø50' },
    holes: { id: 'hole0', z: 0, r: 5, side: -1, s: '4 отв. Ø10', t: '4 отверстия Ø10', d: 'на окружности Ø95, через 90°' }
  },
  quiz: [
    { id: 'flange', q: 'Покажи фланец' }, { id: 'cone', q: 'Покажи усечённый конус' },
    { id: 'pyr', q: 'Покажи материал, вынутый сквозным пирамидальным отверстием' }, { id: 'holes', q: 'Покажи материал, вынутый отверстиями Ø10' }
  ]
};
